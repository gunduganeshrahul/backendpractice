 const {Model,DataTypes}=require('sequelize')
 module.exports=(sequelize)=>
 {
    class UserMaster extends Model{}
    UserMaster.init(
        {
            UserMasterID:
            {
                type:DataTypes.INTEGER,
                allowNull:false,
                primaryKey:true,
            },
            BranchID:
            {
                type:DataTypes.INTEGER,
                allowNull:false,
                references:
                {
                    model:"Branch",
                    key:"BranchID",
                },
            },
            UserMasterName:
            {
                type:DataTypes.STRING,
                allowNull:false,
            },
            Email:
            {
                type:DataTypes.STRING,
            },
            Password:
            {
                type:DataTypes.STRING,
                allowNull:false,
            },
            IsActive:
            {
                type:DataTypes.BOOLEAN,
                defaultValue:true,
            },
        },
        {
            sequelize,
            modelName:"UserMaster",
            tableName:"UserMaster",
        },
    );
    return UserMaster;
 };