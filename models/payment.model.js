const {Model,DataTypes} = require('sequelize')
module.exports=(sequelize)=>
{
    class Payment extends Model{}
    Payment.init(
        {
            PaymentID:
            {
                type:DataTypes.INTEGER,
                allowNull:false,
                primaryKey:true,
                autoIncrement:true,
            },
            OrderID:
            {
                type:DataTypes.STRING,
                allowNull:false,
            },
            RazorpayOrderID:
            {
                type:DataTypes.STRING,
                allowNull:true,
            },
            RazorpayPaymentID:
            {
                type:DataTypes.STRING,
                allowNull:true,
            },
            Amount:
            {
                type:DataTypes.DECIMAL(10,2),
                allowNull:false,
            },
            Currency:
            {
                type:DataTypes.STRING(10),
                allowNull:false,
                defaultValue:"INR",
            },
            Status:
            {
                type:DataTypes.STRING(30),
                allowNull:false,
                defaultValue:"CREATED",
            },
            Signature:
            {
                type:DataTypes.STRING(255),
                allowNull:true
            },
        },
        {
            sequelize,
            tableName:"Payment",
            modelName:"Payment",
            timestamps:true,
        },
    );
    return Payment;
};